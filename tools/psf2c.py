#!/usr/bin/env python3
"""Convert a PC Screen Font (PSF1/PSF2, optionally gzipped) to a C header.

Usage: psf2c.py FONT.psf[.gz] OUT.h

Emits glyphs for ASCII 0x20..0x7E plus a few UI symbols mapped onto
control codes 0x01..0x0F (see EXTRA). Only 8-pixel-wide fonts are supported.

src/font8x16.h was generated with:
    python3 tools/psf2c.py /usr/share/consolefonts/Lat15-Fixed16.psf.gz src/font8x16.h
(Debian/Ubuntu package console-setup-linux; the Fixed fonts are public domain.)
"""
import gzip
import os
import struct
import sys

# control code -> (unicode candidates, comment)
EXTRA = {
    0x01: ([0x25C4, 0x25C0, 0x2190], "left triangle"),
    0x02: ([0x25BA, 0x25B6, 0x2192], "right triangle"),
    0x03: ([0x25B2, 0x2191], "up triangle"),
    0x04: ([0x25BC, 0x2193], "down triangle"),
    0x05: ([0x25CF, 0x2022], "black circle"),
    0x06: ([0x25CB, 0x00B0], "white circle"),
    0x07: ([0x2588], "full block"),
    0x08: ([0x2591], "light shade"),
    0x09: ([0x00B7], "middle dot"),
    0x0A: ([0x00B0], "degree"),
    0x0B: ([0x2190], "left arrow"),
    0x0C: ([0x2192], "right arrow"),
    0x0D: ([0x2191], "up arrow"),
    0x0E: ([0x2193], "down arrow"),
    0x0F: ([0x2261, 0x2550], "menu bars"),
}


def load(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    if data[:2] == b"\x36\x04":
        mode, height = data[2], data[3]
        count = 512 if mode & 1 else 256
        width, size, off = 8, height, 4
        glyphs = [data[off + i * size: off + (i + 1) * size] for i in range(count)]
        umap = {}
        if mode & 2:
            p, g = off + count * size, 0
            while g < count and p + 1 < len(data):
                (u,) = struct.unpack_from("<H", data, p)
                p += 2
                if u == 0xFFFF:
                    g += 1
                elif u == 0xFFFE:  # start of combining sequences: skip to glyph end
                    while struct.unpack_from("<H", data, p)[0] != 0xFFFF:
                        p += 2
                else:
                    umap.setdefault(u, g)
        return width, height, glyphs, umap
    if data[:4] == b"\x72\xb5\x4a\x86":
        _, hdr, flags, count, size, height, width = struct.unpack_from("<7I", data, 4)
        glyphs = [data[hdr + i * size: hdr + (i + 1) * size] for i in range(count)]
        umap = {}
        if flags & 1:
            p, g = hdr + count * size, 0
            while g < count and p < len(data):
                end = p
                while data[end] not in (0xFE, 0xFF):
                    end += 1
                for ch in data[p:end].decode("utf-8", "replace"):
                    umap.setdefault(ord(ch), g)
                while data[end] != 0xFF:
                    end += 1
                p, g = end + 1, g + 1
        return width, height, glyphs, umap
    sys.exit("not a PSF font: %s" % path)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    width, height, glyphs, umap = load(src)
    if width != 8:
        sys.exit("only 8-pixel-wide fonts are supported (got %d)" % width)

    def glyph(cp):
        return glyphs[umap.get(cp, cp)]

    rows = {}
    for cp in range(0x20, 0x7F):
        rows[cp] = (glyph(cp), repr(chr(cp)) if cp != 0x5C else "'\\\\'")
    for code, (cands, name) in EXTRA.items():
        hit = next((c for c in cands if c in umap), None)
        if hit is None:
            print("warning: no glyph for %s" % name, file=sys.stderr)
            rows[code] = (bytes(height), name + " (missing)")
        else:
            rows[code] = (glyphs[umap[hit]], "%s U+%04X" % (name, hit))

    lines = [
        "/* Generated by tools/psf2c.py from %s. Do not edit. */" % os.path.basename(src),
        "/* Source: console-setup \"Fixed\" console font, public domain. */",
        "#ifndef FONT8X16_H",
        "#define FONT8X16_H",
        "",
        "#include <stdint.h>",
        "",
        "#define FONT_W     8",
        "#define FONT_H     %d" % height,
        "#define FONT_COUNT 0x7F",
        "",
        "/* index = character code; 0x01..0x0F hold UI symbols, unlisted codes are blank */",
        "static const uint8_t font8x16[FONT_COUNT][FONT_H] = {",
    ]
    for code in sorted(rows):
        bits, note = rows[code]
        body = ", ".join("0x%02X" % b for b in bits[:height])
        lines.append("    [0x%02X] = {%s}, /* %s */" % (code, body, note.replace("*/", "* /")))
    lines += ["};", "", "#endif", ""]
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %d glyphs, %dx%d" % (out, len(rows), width, height))


if __name__ == "__main__":
    main()
